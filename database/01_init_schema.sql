-- =============================================================================
-- Ate Platform - Initial Schema DDL (PostgreSQL 16)
-- Clean Architecture Identity & Onboarding Core
-- Tables: roles, users, persons, user_roles, companies (users.company_id), employees,
--         refresh_tokens, password_recoveries, user_external_logins, restaurants, restaurant_dishes,
--         company_restaurant_agreements
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 1. ROLES
CREATE TABLE IF NOT EXISTS roles (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    description VARCHAR(200) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_roles_name UNIQUE (name)
);

-- 2. USERS
CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email VARCHAR(255) NULL,
    password_hash VARCHAR(255) NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    email_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    last_login_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by UUID NULL,
    updated_at TIMESTAMPTZ NULL,
    updated_by UUID NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ NULL,
    deleted_by UUID NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_users_email 
ON users(email) 
WHERE email IS NOT NULL AND is_deleted = FALSE;

-- 3. PERSONS
CREATE TABLE IF NOT EXISTS persons (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    document_type VARCHAR(20) NOT NULL DEFAULT 'NationalId',
    document_number VARCHAR(30) NOT NULL,
    phone_number VARCHAR(30) NULL,
    avatar_url VARCHAR(500) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by UUID NULL,
    updated_at TIMESTAMPTZ NULL,
    updated_by UUID NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ NULL,
    deleted_by UUID NULL,
    CONSTRAINT fk_persons_users FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT uq_persons_user_id UNIQUE (user_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_persons_document 
ON persons(document_type, document_number) 
WHERE is_deleted = FALSE;

-- 4. USER_ROLES (M:N)
CREATE TABLE IF NOT EXISTS user_roles (
    user_id UUID NOT NULL,
    role_id INT NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_users FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_roles FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE
);

-- 5. COMPANIES
CREATE TABLE IF NOT EXISTS companies (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    business_name VARCHAR(150) NOT NULL,
    trade_name VARCHAR(150) NOT NULL,
    tax_id VARCHAR(20) NOT NULL,
    email VARCHAR(100) NULL,
    phone VARCHAR(30) NULL,
    address VARCHAR(300) NULL,
    logo_url VARCHAR(500) NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by UUID NULL,
    updated_at TIMESTAMPTZ NULL,
    updated_by UUID NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ NULL,
    deleted_by UUID NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_companies_tax_id
ON companies(tax_id)
WHERE is_deleted = FALSE;

ALTER TABLE companies ADD COLUMN IF NOT EXISTS logo_url VARCHAR(500) NULL;
ALTER TABLE companies ADD COLUMN IF NOT EXISTS latitude NUMERIC(9,6) NULL;
ALTER TABLE companies ADD COLUMN IF NOT EXISTS longitude NUMERIC(9,6) NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_companies_location') THEN
        ALTER TABLE companies
            ADD CONSTRAINT ck_companies_location CHECK (
                (latitude IS NULL AND longitude IS NULL)
                OR (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180)
            );
    END IF;
END $$;

-- 5.1 USERS -> COMPANIES (Company administrators belong to one company)
ALTER TABLE users ADD COLUMN IF NOT EXISTS company_id UUID NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_users_companies'
    ) THEN
        ALTER TABLE users
        ADD CONSTRAINT fk_users_companies FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE RESTRICT;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_users_company_id
ON users(company_id)
WHERE company_id IS NOT NULL AND is_deleted = FALSE;

-- 6. EMPLOYEES
CREATE TABLE IF NOT EXISTS employees (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    company_id UUID NOT NULL,
    person_id UUID NOT NULL,
    employee_code VARCHAR(50) NULL,
    department VARCHAR(100) NULL,
    monthly_allowance NUMERIC(12,2) NOT NULL DEFAULT 0,
    is_intern BOOLEAN NOT NULL DEFAULT FALSE,
    qr_code_token VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by UUID NULL,
    updated_at TIMESTAMPTZ NULL,
    updated_by UUID NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ NULL,
    deleted_by UUID NULL,
    CONSTRAINT fk_employees_companies FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE RESTRICT,
    CONSTRAINT fk_employees_persons FOREIGN KEY (person_id) REFERENCES persons(id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_employees_qr_code_token 
ON employees(qr_code_token) 
WHERE is_deleted = FALSE;

CREATE UNIQUE INDEX IF NOT EXISTS ix_employees_company_person
ON employees(company_id, person_id)
WHERE is_deleted = FALSE;

ALTER TABLE employees ADD COLUMN IF NOT EXISTS monthly_allowance NUMERIC(12,2) NOT NULL DEFAULT 0;
ALTER TABLE employees ADD COLUMN IF NOT EXISTS is_intern BOOLEAN NOT NULL DEFAULT FALSE;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'ck_employees_monthly_allowance'
    ) THEN
        ALTER TABLE employees
        ADD CONSTRAINT ck_employees_monthly_allowance CHECK (monthly_allowance >= 0);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_employees_company_id
ON employees(company_id)
WHERE is_deleted = FALSE;

-- 7. REFRESH_TOKENS
CREATE TABLE IF NOT EXISTS refresh_tokens (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL,
    token VARCHAR(255) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    is_revoked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_refresh_tokens_users FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uq_refresh_tokens_token UNIQUE (token)
);

-- 7b. PASSWORD_RECOVERIES (código OTP para restablecer la contraseña)
-- Solo se guardan hashes. El código vence en code_expires_at; al verificarlo se emite un
-- token de un solo uso que vence en reset_token_expires_at.
CREATE TABLE IF NOT EXISTS password_recoveries (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL,
    code_hash VARCHAR(128) NOT NULL,
    code_expires_at TIMESTAMPTZ NOT NULL,
    attempts INT NOT NULL DEFAULT 0,
    code_verified_at TIMESTAMPTZ NULL,
    reset_token_hash VARCHAR(128) NULL,
    reset_token_expires_at TIMESTAMPTZ NULL,
    used_at TIMESTAMPTZ NULL,
    invalidated_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_password_recoveries_users FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_password_recoveries_user_created
ON password_recoveries(user_id, created_at DESC);

CREATE UNIQUE INDEX IF NOT EXISTS ix_password_recoveries_reset_token
ON password_recoveries(reset_token_hash)
WHERE reset_token_hash IS NOT NULL;

-- 8. USER_EXTERNAL_LOGINS (Active Directory / Azure AD)
CREATE TABLE IF NOT EXISTS user_external_logins (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL,
    provider VARCHAR(50) NOT NULL,
    provider_key VARCHAR(255) NOT NULL,
    provider_display_name VARCHAR(150) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_external_logins_users FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uq_external_logins_provider_key UNIQUE (provider, provider_key)
);

-- 9. RESTAURANTS (Affiliated restaurants / merchants)
CREATE TABLE IF NOT EXISTS restaurants (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    merchant_user_id UUID NULL,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(150) NOT NULL,
    cuisine VARCHAR(80) NOT NULL,
    address VARCHAR(300) NULL,
    phone VARCHAR(30) NULL,
    latitude NUMERIC(9,6) NULL,
    longitude NUMERIC(9,6) NULL,
    brand_color VARCHAR(7) NOT NULL,
    -- TEMPORAL: guarda el logo serializado como data URL base64 hasta tener el servidor de imágenes.
    logo_url TEXT NULL,
    icon VARCHAR(30) NULL,
    ready_minutes INT NOT NULL DEFAULT 15,
    breakfast_cutoff TIME NULL,
    lunch_cutoff TIME NULL,
    dinner_cutoff TIME NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by UUID NULL,
    updated_at TIMESTAMPTZ NULL,
    updated_by UUID NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ NULL,
    deleted_by UUID NULL,
    CONSTRAINT fk_restaurants_users FOREIGN KEY (merchant_user_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT ck_restaurants_ready_minutes CHECK (ready_minutes >= 0)
);

ALTER TABLE restaurants ADD COLUMN IF NOT EXISTS latitude NUMERIC(9,6) NULL;
ALTER TABLE restaurants ADD COLUMN IF NOT EXISTS longitude NUMERIC(9,6) NULL;

-- TEMPORAL: el logo viaja serializado (data URL base64) hasta que exista el servidor de imágenes.
-- Cuando exista, volver a VARCHAR(500) con la URL pública del archivo.
ALTER TABLE restaurants ALTER COLUMN logo_url TYPE TEXT;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_restaurants_location') THEN
        ALTER TABLE restaurants
            ADD CONSTRAINT ck_restaurants_location CHECK (
                (latitude IS NULL AND longitude IS NULL)
                OR (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180)
            );
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS ix_restaurants_code
ON restaurants(code)
WHERE is_deleted = FALSE;

CREATE INDEX IF NOT EXISTS ix_restaurants_merchant_user_id
ON restaurants(merchant_user_id)
WHERE merchant_user_id IS NOT NULL AND is_deleted = FALSE;

-- 10. RESTAURANT_DISHES (Menu per meal type: breakfast, lunch, dinner)
CREATE TABLE IF NOT EXISTS restaurant_dishes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    restaurant_id UUID NOT NULL,
    meal_type VARCHAR(20) NOT NULL,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(300) NOT NULL DEFAULT '',
    protein VARCHAR(30) NOT NULL DEFAULT '',
    has_rice BOOLEAN NOT NULL DEFAULT FALSE,
    default_drink VARCHAR(50) NOT NULL DEFAULT 'Jugo',
    price NUMERIC(10,2) NOT NULL DEFAULT 0,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by UUID NULL,
    updated_at TIMESTAMPTZ NULL,
    updated_by UUID NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ NULL,
    deleted_by UUID NULL,
    CONSTRAINT fk_restaurant_dishes_restaurants FOREIGN KEY (restaurant_id) REFERENCES restaurants(id) ON DELETE RESTRICT,
    CONSTRAINT ck_restaurant_dishes_meal_type CHECK (meal_type IN ('breakfast', 'lunch', 'dinner')),
    CONSTRAINT ck_restaurant_dishes_price CHECK (price >= 0)
);

CREATE INDEX IF NOT EXISTS ix_restaurant_dishes_restaurant_meal
ON restaurant_dishes(restaurant_id, meal_type)
WHERE is_deleted = FALSE;

-- 11. COMPANY_RESTAURANT_AGREEMENTS (Which restaurants each client company offers)
CREATE TABLE IF NOT EXISTS company_restaurant_agreements (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    company_id UUID NOT NULL,
    restaurant_id UUID NOT NULL,
    distance_m INT NOT NULL DEFAULT 0,
    starts_on DATE NOT NULL DEFAULT CURRENT_DATE,
    ends_on DATE NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by UUID NULL,
    updated_at TIMESTAMPTZ NULL,
    updated_by UUID NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ NULL,
    deleted_by UUID NULL,
    CONSTRAINT fk_agreements_companies FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE RESTRICT,
    CONSTRAINT fk_agreements_restaurants FOREIGN KEY (restaurant_id) REFERENCES restaurants(id) ON DELETE RESTRICT,
    CONSTRAINT ck_agreements_distance CHECK (distance_m >= 0),
    CONSTRAINT ck_agreements_dates CHECK (ends_on IS NULL OR ends_on >= starts_on)
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_agreements_company_restaurant
ON company_restaurant_agreements(company_id, restaurant_id)
WHERE is_deleted = FALSE;

-- 12. ACHIEVEMENTS (Employee trophies, PlayStation style)
-- The catalog is data: a new trophy over an existing metric is one row here, no code change.
-- Progress is a cache that can always be recomputed from employee_orders (MongoDB).
CREATE TABLE IF NOT EXISTS achievement_definitions (
    code VARCHAR(50) PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    description VARCHAR(200) NOT NULL,
    tier VARCHAR(10) NOT NULL,
    icon VARCHAR(30) NOT NULL,
    metric VARCHAR(40) NOT NULL,
    threshold INT NOT NULL,
    is_hidden BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_achievement_definitions_tier CHECK (tier IN ('bronze', 'silver', 'gold', 'platinum')),
    CONSTRAINT ck_achievement_definitions_threshold CHECK (threshold > 0)
);

CREATE TABLE IF NOT EXISTS user_achievements (
    user_id UUID NOT NULL,
    achievement_code VARCHAR(50) NOT NULL,
    progress INT NOT NULL DEFAULT 0,
    unlocked_at TIMESTAMPTZ NULL,
    seen_at TIMESTAMPTZ NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_user_achievements PRIMARY KEY (user_id, achievement_code),
    CONSTRAINT fk_user_achievements_users FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_achievements_definitions FOREIGN KEY (achievement_code) REFERENCES achievement_definitions(code) ON DELETE CASCADE,
    CONSTRAINT ck_user_achievements_progress CHECK (progress >= 0)
);

-- Unlocked trophies the employee has not seen yet (the unlock toast reads this).
CREATE INDEX IF NOT EXISTS ix_user_achievements_unseen
ON user_achievements(user_id)
WHERE unlocked_at IS NOT NULL AND seen_at IS NULL;

